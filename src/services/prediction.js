export async function generateForecastPrediction(selection, onChunk, onCalculated) {
  const report = buildTransitReport({ ...selection, includeDaily: false })
  onCalculated?.(report)
  return streamPrediction(buildForecastPostMessages(selection, report), onChunk)
}

async function streamPrediction(messages, onChunk) {
  const apiKey = import.meta.env.VITE_OPENAI_API_KEY
  if (!apiKey || apiKey === 'your_api_key_here') throw new Error('ยังไม่ได้ตั้งค่า OpenAI API key')
  const client = new OpenAI({ apiKey, dangerouslyAllowBrowser: true })
  const stream = await client.chat.completions.create({ model: import.meta.env.VITE_OPENAI_MODEL || 'gpt-6-luna', reasoning_effort: 'none', messages, stream: true })
  for await (const chunk of stream) {
    const text = chunk.choices[0]?.delta?.content
    if (text) onChunk(text)
  }
}
